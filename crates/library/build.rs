//! Embeds the built-in library.
//!
//! Every `*.md` file in `<workspace>/library/ultimate-rust-bundle/` (names
//! starting with `_` are drafts and skipped) is baked into the binary with
//! `include_str!`, in lexical filename order, so the shipped app needs no
//! resource folder. An empty or missing folder produces an empty library.

#[path = "src/scan.rs"]
mod scan;

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

const LIBRARY_FOLDER: &str = "ultimate-rust-bundle";

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    // crates/library -> crates -> <workspace>
    let workspace = manifest
        .parent()
        .and_then(Path::parent)
        .expect("crates/library sits two levels below the workspace root");
    let dir = workspace.join("library").join(LIBRARY_FOLDER);

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/scan.rs");
    println!("cargo:rerun-if-changed={}", dir.display());

    let files = scan::list_markdown(&dir).unwrap_or_default();

    let mut out = String::from("// @generated by build.rs. Do not edit.\n");
    out.push_str("pub(crate) static BUILTIN: &[(&str, &str)] = &[\n");
    for (name, path) in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        // Fail here, with the file named, instead of deep inside include_str!.
        if let Err(e) = fs::read_to_string(path) {
            panic!("library file {} cannot be embedded: {e}", path.display());
        }
        // `{:?}` on a str is a valid Rust string literal, backslashes escaped.
        writeln!(
            out,
            "    ({name:?}, include_str!({:?})),",
            path.to_string_lossy()
        )
        .expect("write to String");
    }
    out.push_str("];\n");

    let target = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("builtin.rs");
    fs::write(&target, out).expect("write builtin.rs");
}
